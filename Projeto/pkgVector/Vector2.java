package pkgVector;

/**
 * Classe contendo os atributos de um Vector2 utilizados pelo programa.
 * 
 * @author Arthur Daniel, Arthur Oliveira, João Paulo
 * @version 2026/06/02 (YYYY/MM/DD)
 */

public class Vector2{
    //Atributos principais.
    public int x, y;
    
    /**
     * Construtor de classe.
     * 
     * @param x (Int) Valor X do Vector2.
     * @param y (Int) Valor Y do Vector2.
     */
    
    public Vector2(int x, int y){
        this.x = x;
        this.y = y;
    }
}