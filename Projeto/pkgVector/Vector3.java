package pkgVector;

/**
 * Classe contendo os atributos de um Vector3 utilizado pelo programa.
 * 
 * @author Arthur Daniel, Arthur Oliveira, João Paulo
 * @version 2026/06/02 (YYYY/MM/DD)
 */

public class Vector3{
    //Atributos principais.
    public int x, y, z;
    
    /**
     * Construtor de classe.
     * 
     * @param x (Int) Valor X do Vector3.
     * @param y (Int) Valor Y do Vector3.
     * @param z (Int) Valor Z do Vector3.
     */
    
    public Vector3(int x, int y, int z){
        this.x = x;
        this.y = y;
        this.z = z;
    }
}